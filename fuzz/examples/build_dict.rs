//! Print the libFuzzer dictionary for text targets to stdout.
//!
//! `cargo run --example build_dict --no-default-features > dicts/expr.dict`
//!
//! Every function, method, and property name comes from the live function
//! library, so a newly registered function is in the dictionary as soon as
//! the dictionary is regenerated — and `tests/replay.rs` fails until it is.

